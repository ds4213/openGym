export function programText(key, ...values) {
  const pack = getLang() === 'zh-TW' ? zhTW : getLang() === 'zh' ? zh : null
  return values.reduce((text, value, index) => text.replaceAll(`{${index}}`, value), pack?.[key] || key)
}
